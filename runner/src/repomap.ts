/**
 * Repository-Übersicht für den Auftrag (ohne Tokens, nur aus git): Ordner mit Dateizahlen, Sprachen, wichtige
 * Dateien und die Skripte aus `package.json`. Spart dem Agent das Erkunden des Baums (`ls`, `find`, viele Aufrufe).
 * Zwischengespeichert je Tree-SHA unter `WORK_DIR/meta/repomap/<owner>/<repo>/<tree>.md` (die letzten 10 je Repo).
 */
import { mkdir, readdir, readFile, rm, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import type { RepoRef, Workspace } from './git/workspace.ts';

/** Höchstlänge der Übersicht (Zeichen) */
export const REPO_MAP_MAX = 3000;
const KEEP = 10;

const KEY_FILES =
	/^(readme(\.\w+)?|agents\.md|claude\.md|contributing\.md|package\.json|pnpm-workspace\.yaml|turbo\.json|nx\.json|tsconfig\.json|vite\.config\.\w+|svelte\.config\.\w+|next\.config\.\w+|cargo\.toml|go\.mod|pyproject\.toml|requirements\.txt|setup\.py|pom\.xml|build\.gradle(\.kts)?|composer\.json|gemfile|makefile|justfile|dockerfile|docker-compose\.ya?ml|compose\.ya?ml|\.nvmrc|\.tool-versions)$/i;

interface Dir {
	files: number;
	children: Map<string, number>;
}

/** Übersicht aus der Dateiliste (`git ls-files`) und optional dem Inhalt von `package.json` */
export function formatRepoMap(files: string[], packageJson: string | null): string {
	const dirs = new Map<string, Dir>();
	const rootFiles: string[] = [];
	const ext = new Map<string, number>();
	const keyFiles: string[] = [];
	for (const f of files) {
		const parts = f.split('/');
		const base = parts.at(-1) ?? f;
		if (parts.length <= 3 && (KEY_FILES.test(base) || /^\.github\/workflows\/[^/]+$/.test(f))) keyFiles.push(f);
		const e = /\.([A-Za-z0-9]{1,8})$/.exec(base)?.[1]?.toLowerCase();
		if (e) ext.set(e, (ext.get(e) ?? 0) + 1);
		if (parts.length === 1) {
			rootFiles.push(f);
			continue;
		}
		const top = parts[0]!;
		const d = dirs.get(top) ?? { files: 0, children: new Map() };
		d.files++;
		if (parts.length > 2) d.children.set(parts[1]!, (d.children.get(parts[1]!) ?? 0) + 1);
		dirs.set(top, d);
	}
	const out: string[] = [`${files.length} tracked files.`, '', 'Top-level directories (files):'];
	const sorted = [...dirs.entries()].sort((a, b) => b[1].files - a[1].files);
	for (const [name, d] of sorted.slice(0, 25)) {
		const kids = [...d.children.entries()].sort((a, b) => b[1] - a[1]).slice(0, 8);
		const detail = kids.length ? ` – ${kids.map(([k, n]) => `${k}/ (${n})`).join(', ')}` : '';
		out.push(`- ${name}/ (${d.files})${detail}`);
	}
	if (sorted.length > 25) out.push(`- … ${sorted.length - 25} more`);
	if (rootFiles.length) out.push('', `Root files: ${rootFiles.slice(0, 30).join(', ')}${rootFiles.length > 30 ? ', …' : ''}`);
	const langs = [...ext.entries()].sort((a, b) => b[1] - a[1]).slice(0, 10);
	if (langs.length) out.push('', `File types: ${langs.map(([e, n]) => `.${e} ${n}`).join(', ')}`);
	if (keyFiles.length) out.push('', `Key files: ${keyFiles.slice(0, 30).join(', ')}`);
	const scripts = scriptsOf(packageJson);
	if (scripts.length) out.push('', 'package.json scripts:', ...scripts.map(([k, v]) => `- \`${k}\`: \`${v}\``));
	const text = out.join('\n');
	return text.length <= REPO_MAP_MAX ? text : `${text.slice(0, REPO_MAP_MAX - 2)}…`;
}

function scriptsOf(json: string | null): [string, string][] {
	if (!json) return [];
	try {
		const s = (JSON.parse(json) as { scripts?: unknown }).scripts;
		if (!s || typeof s !== 'object') return [];
		return Object.entries(s as Record<string, unknown>)
			.filter((e): e is [string, string] => typeof e[1] === 'string')
			.slice(0, 20)
			.map(([k, v]) => [k.slice(0, 40), v.replace(/`/g, "'").slice(0, 120)]);
	} catch {
		return [];
	}
}

/** Abschnitt für den Auftrag */
export function repoMapSection(map: string): string {
	return [
		'## Repository overview (generated by the runner from git – no need to list the tree yourself)',
		'',
		map
	].join('\n');
}

/**
 * Übersicht für den Stand von HEAD im Worktree `dir` (aus dem Zwischenspeicher, sonst neu erzeugt).
 * Fehler → `null` (die Übersicht ist nur eine Hilfe).
 */
export async function repoMap(ws: Workspace, repo: RepoRef, dir: string): Promise<string | null> {
	try {
		const tree = (await ws.run(dir, ['rev-parse', 'HEAD^{tree}'])).stdout.trim();
		if (!/^[0-9a-f]{40,64}$/.test(tree)) return null;
		const cacheDir = path.join(ws.o.workDir, 'meta', 'repomap', repo.repoOwner, repo.repoName);
		const file = path.join(cacheDir, `${tree}.md`);
		const cached = await readFile(file, 'utf8').catch(() => null);
		if (cached !== null) return cached;
		const ls = await ws.run(dir, ['ls-files', '-z'], { maxStdoutBytes: 50_000_000 });
		const files = ls.stdout.split('\0').filter(Boolean);
		if (!files.length) return null;
		const pkg = files.includes('package.json')
			? (await ws.run(dir, ['show', 'HEAD:package.json'], { allowFail: true })).stdout
			: null;
		const map = formatRepoMap(files, pkg);
		await mkdir(cacheDir, { recursive: true });
		await writeFile(file, map, 'utf8');
		await prune(cacheDir);
		return map;
	} catch {
		return null;
	}
}

async function prune(dir: string): Promise<void> {
	const names = (await readdir(dir).catch(() => [] as string[])).filter((n) => n.endsWith('.md'));
	if (names.length <= KEEP) return;
	const withTime = await Promise.all(
		names.map(async (n) => ({ n, t: (await stat(path.join(dir, n)).catch(() => null))?.mtimeMs ?? 0 }))
	);
	withTime.sort((a, b) => b.t - a.t);
	for (const { n } of withTime.slice(KEEP)) await rm(path.join(dir, n), { force: true }).catch(() => undefined);
}
